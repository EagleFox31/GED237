# backend/scripts/restore_policies.py
#!/usr/bin/env python3
"""
Restore AuthZ policies from a backup directory.

Usage:
  python scripts/restore_policies.py --backup-dir ./backups/authz/authz_backup_YYYYMMDDTHHMMSSZ
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import shutil
from pathlib import Path
import sys

from sqlalchemy import create_engine, text

BACKEND_ROOT = Path(__file__).resolve().parent.parent
if str(BACKEND_ROOT) not in sys.path:
    sys.path.insert(0, str(BACKEND_ROOT))


def _ensure_async_database_url_env() -> None:
    """
    Importing app modules initializes async SQLAlchemy engine from DATABASE_URL.
    When DATABASE_URL is sync-style in subprocess tests, normalize it first.
    """
    url = os.environ.get("DATABASE_URL", "")
    if url.startswith("sqlite:///"):
        os.environ["DATABASE_URL"] = url.replace(
            "sqlite:///", "sqlite+aiosqlite:///", 1
        )
    elif url.startswith("postgresql://"):
        os.environ["DATABASE_URL"] = url.replace(
            "postgresql://", "postgresql+asyncpg://", 1
        )


def _to_sync_sqlalchemy_url(url: str) -> str:
    if url.startswith("postgresql+asyncpg://"):
        return url.replace("postgresql+asyncpg://", "postgresql://", 1)
    if url.startswith("sqlite+aiosqlite://"):
        return url.replace("sqlite+aiosqlite://", "sqlite://", 1)
    return url


def _policy_csv_path() -> Path:
    return (
        Path(__file__).resolve().parent.parent / "app" / "core" / "authz" / "policy.csv"
    )


def _restore_sql_tables(backup_dir: Path) -> None:
    casbin_payload = json.loads(
        (backup_dir / "casbin_rule.json").read_text(encoding="utf-8")
    )
    version_payload = json.loads(
        (backup_dir / "authz_policy_version.json").read_text(encoding="utf-8")
    )

    policy_url = os.environ.get("AUTHZ_POLICY_DATABASE_URL") or os.environ.get(
        "DATABASE_URL"
    )
    if not policy_url:
        raise SystemExit(
            "Missing AUTHZ_POLICY_DATABASE_URL or DATABASE_URL in environment."
        )
    db_url = _to_sync_sqlalchemy_url(policy_url)
    engine = create_engine(db_url, future=True)
    try:
        with engine.begin() as conn:
            conn.execute(text("DELETE FROM casbin_rule"))
            if casbin_payload:
                conn.execute(
                    text(
                        "INSERT INTO casbin_rule (ptype, v0, v1, v2, v3, v4, v5) "
                        "VALUES (:ptype, :v0, :v1, :v2, :v3, :v4, :v5)"
                    ),
                    casbin_payload,
                )

            conn.execute(
                text(
                    "CREATE TABLE IF NOT EXISTS authz_policy_version ("
                    "id INTEGER PRIMARY KEY, "
                    "version BIGINT NOT NULL)"
                )
            )
            conn.execute(text("DELETE FROM authz_policy_version"))
            if version_payload:
                conn.execute(
                    text(
                        "INSERT INTO authz_policy_version (id, version) VALUES (:id, :version)"
                    ),
                    version_payload,
                )
            else:
                conn.execute(
                    text("INSERT INTO authz_policy_version (id, version) VALUES (1, 1)")
                )
    finally:
        engine.dispose()


async def _reload() -> None:
    _ensure_async_database_url_env()
    try:
        from app.core.authz.casbin_enforcer import reload_enforcer

        await reload_enforcer()
    except ModuleNotFoundError as exc:
        # Some local/test envs may not include optional async DB drivers (e.g. aiosqlite).
        # Restore itself is already done at SQL level; skip in-process reload gracefully.
        if exc.name in {"aiosqlite", "asyncpg"}:
            print(
                f"[restore] warning: reload skipped because optional async driver is missing: {exc.name}",
                file=sys.stderr,
            )
            return
        raise


def main() -> None:
    _ensure_async_database_url_env()
    parser = argparse.ArgumentParser(
        description="Restore AuthZ policy sources (CSV + SQL)."
    )
    parser.add_argument(
        "--backup-dir",
        required=True,
        help="Path to backup directory generated by backup_policies.py",
    )
    args = parser.parse_args()

    backup_dir = Path(args.backup_dir)
    if not backup_dir.exists():
        raise SystemExit(f"Backup directory not found: {backup_dir}")

    csv_src = backup_dir / "policy.csv"
    if not csv_src.exists():
        raise SystemExit(f"Missing file: {csv_src}")
    shutil.copy2(csv_src, _policy_csv_path())

    _restore_sql_tables(backup_dir)
    asyncio.run(_reload())
    print("restore_ok")


if __name__ == "__main__":
    main()
